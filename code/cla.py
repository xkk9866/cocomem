"""Counterfactual Lineage Attribution (CLA).

For a unit u = f(S) generated by the compressor LLM from input claims S, the counterfactual
dependence of u on claim c is measured by the compressor's own likelihood:
    Delta(u, c) = log p(u | prompt(S)) - log p(u | prompt(S \\ {c}))
computed with prefill-only requests (vLLM prompt_logprobs).  Per-token deltas give
token-level lineage.  CLA provides the causal supervision used to train the amortized
lineage network (CLE)."""
import argparse
import asyncio
import json
import os
import random

import httpx
from transformers import AutoTokenizer

import prompts
from cocomem import CITE, PROFILE

MODEL_PATH = "/home/yaokang/models/Qwen3-8B-AWQ"
_tok = None


def tok():
    global _tok
    if _tok is None:
        _tok = AutoTokenizer.from_pretrained(MODEL_PATH)
    return _tok


def fact_lines(claims, cids):
    return "\n".join(f"[{c}] ({claims[c]['date'][:10]}, {claims[c]['speaker']}) {claims[c]['text']}" for c in cids)


def unit_prompt(unit, claims, cids):
    if unit["level"] == "note":
        return prompts.NOTE.format(date=unit["date"], words=100, facts=fact_lines(claims, cids))
    if unit["level"] == "digest":
        return prompts.DIGEST.format(words=150, facts=fact_lines(claims, cids))
    return PROFILE.format(words=250, facts=fact_lines(claims, cids))


def ids_for(prompt_text, unit_text):
    """Token ids of chat-formatted prompt + unit, the unit start index, and a mask that excludes
    citation tokens (so that dependence is measured on content, not on the [cX] markers)."""
    t = tok()
    prefix = t.apply_chat_template([{"role": "user", "content": prompt_text}], tokenize=False,
                                   add_generation_prompt=True, enable_thinking=False)
    a = t(prefix, add_special_tokens=False).input_ids
    enc = t(unit_text, add_special_tokens=False, return_offsets_mapping=True)
    spans = [m.span() for m in CITE.finditer(unit_text)]
    mask = [not any(s < e2 and e > s2 for s2, e2 in spans) for s, e in enc.offset_mapping]
    return a + enc.input_ids, len(a), mask, list(enc.offset_mapping)


class Scorer:
    def __init__(self, port=18431, model="qwen3-8b", conc=64):
        self.url = f"http://localhost:{port}/v1/completions"
        self.model = model
        self.sem = asyncio.Semaphore(conc)
        self.client = httpx.AsyncClient(timeout=1800)

    async def token_logprobs(self, ids, start, k=0, full=False):
        """Teacher-forced log-probs of the unit tokens. With full=True also returns each token's rank
        and the best competing log-prob (k>=2), i.e. the greedy-decoding margin."""
        async with self.sem:
            for attempt in range(5):
                try:
                    r = await self.client.post(self.url, json={"model": self.model, "prompt": ids, "max_tokens": 1,
                                                               "temperature": 0, "prompt_logprobs": k})
                    plp = r.json()["choices"][0]["prompt_logprobs"]
                    break
                except Exception:
                    if attempt == 4:
                        raise
                    await asyncio.sleep(3)
        lps, ranks, alts = [], [], []
        for i in range(start, len(ids)):
            d = plp[i] or {}
            v = d.get(str(ids[i]))
            lps.append(v["logprob"] if v else (min(x["logprob"] for x in d.values()) if d else 0.0))
            ranks.append(int(v.get("rank") or 1) if v else 99)
            others = [x["logprob"] for t, x in d.items() if t != str(ids[i])]
            alts.append(max(others) if others else -99.0)
        return (lps, ranks, alts) if full else lps

    async def attribute(self, unit, claims, cand=None, keep=0.5):
        """Counterfactual lineage of `unit` w.r.t. candidate input claims (default: all inputs).
        Returns {cid: (delta_total, delta_max, [(char_start, char_end, delta), ...])}; the token list
        keeps tokens with |delta| > keep and is expressed in characters of unit['text_cited']."""
        inputs = list(unit["inputs"])
        cand = inputs if cand is None else cand
        text = unit["text_cited"]
        ids, st, mask, offs = ids_for(unit_prompt(unit, claims, inputs), text)
        base, brank, balt = await self.token_logprobs(ids, st, k=2, full=True)

        async def ablate(c):
            rest = [x for x in inputs if x != c]
            ids2, st2, _, _ = ids_for(unit_prompt(unit, claims, rest), text)
            lp, rk, _ = await self.token_logprobs(ids2, st2, k=0, full=True)
            d = [(b - a) if k else 0.0 for b, a, k in zip(base, lp, mask)]
            # flip: the token was the greedy choice under S but is no longer under S \ {c}
            flip = [bool(k and r0 == 1 and r1 > 1) for k, r0, r1 in zip(mask, brank, rk)]
            toks = [(int(o[0]), int(o[1]), round(float(x), 3), int(f)) for o, x, f in zip(offs, d, flip)
                    if abs(x) > keep or f]
            return c, (float(sum(d)), float(max(d) if d else 0.0), toks)

        res = await asyncio.gather(*(ablate(c) for c in cand))
        return dict(res)


async def main(args):
    """Collect CLA labels for units of the given built states (training data for CLE)."""
    from splits import make_splits
    sp = make_splits()
    qids = []
    for s in args.splits.split(","):
        qids += sp[s]
    rng = random.Random(args.seed)
    sc = Scorer(conc=args.conc)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    done = set()
    if os.path.exists(args.out):
        for line in open(args.out):
            r = json.loads(line)
            done.add((r["qid"], r["uid"]))
    jobs = []
    for q in qids:
        p = f"/data/yaokang/corrmem/states/cocomem/{q}.json"
        if not os.path.exists(p):
            continue
        st = json.load(open(p))
        units = list(st["units"].values())
        notes = [u for u in units if u["level"] == "note" and u["inputs"]]
        rng.shuffle(notes)
        pick = notes[:args.notes] + [u for u in units if u["level"] == "digest"]
        if args.profiles and rng.random() < args.profiles:
            pick += [u for u in units if u["level"] == "profile"]
        for u in pick:
            if (q, u["id"]) in done:
                continue
            cand = None
            if u["level"] == "profile" and len(u["inputs"]) > args.prof_cand:
                cited = [c for c in u["cited"] if c in u["inputs"]]
                rest = [c for c in u["inputs"] if c not in cited]
                rng.shuffle(cited)
                rng.shuffle(rest)
                k = args.prof_cand // 2
                cand = cited[:k] + rest[:args.prof_cand - min(k, len(cited))]
            jobs.append((q, u, st["claims"], cand))
    print("jobs", len(jobs), flush=True)
    fout = open(args.out, "a")
    n = 0

    async def one(q, u, claims, cand):
        nonlocal n
        try:
            att = await sc.attribute(u, claims, cand)
        except Exception as e:
            print("ERR", q, u["id"], e, flush=True)
            return
        fout.write(json.dumps({"qid": q, "uid": u["id"], "level": u["level"], "text": u["text_cited"],
                               "inputs": u["inputs"], "cited": u["cited"],
                               "claims": {c: claims[c]["text"] for c in att},
                               "delta": {c: v[0] for c, v in att.items()},
                               "delta_max": {c: v[1] for c, v in att.items()},
                               "tokens": {c: v[2] for c, v in att.items()}}) + "\n")
        fout.flush()
        n += 1
        if n % 50 == 0:
            print("done", n, flush=True)

    await asyncio.gather(*(one(*j) for j in jobs))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--splits", default="train")
    ap.add_argument("--out", default="/data/yaokang/corrmem/data/cla_train.jsonl")
    ap.add_argument("--notes", type=int, default=8)
    ap.add_argument("--profiles", type=float, default=0.3)
    ap.add_argument("--prof_cand", type=int, default=40)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--conc", type=int, default=48)
    asyncio.run(main(ap.parse_args()))
